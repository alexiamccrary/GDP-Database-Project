USE aem432_custom;
CREATE TABLE CONTINENT (
    Continent_ID INT AUTO_INCREMENT,
    Continent_Name VARCHAR(100) NOT NULL,
    CONSTRAINT PK_CONTINENT PRIMARY KEY (Continent_ID)
);

CREATE TABLE COUNTRY (
    Country_ID INT AUTO_INCREMENT,
    Country_Name VARCHAR(100) NOT NULL,
    Continent_ID INT NOT NULL,
    CONSTRAINT PK_COUNTRY PRIMARY KEY (Country_ID)
);

CREATE TABLE YEAR (
    Year_ID INT AUTO_INCREMENT,
    Year_Value INT NOT NULL,
    CONSTRAINT PK_YEAR PRIMARY KEY (Year_ID)
);

CREATE TABLE COUNTRY_STATISTICS (
    Statistic_ID INT AUTO_INCREMENT,
    Country_ID INT NOT NULL,
    Year_ID INT NOT NULL,
    Population INT DEFAULT 0,
    GDP_USD DECIMAL(18,2) DEFAULT 0.00,
    CONSTRAINT PK_COUNTRY_STATISTICS PRIMARY KEY (Statistic_ID)
);

ALTER TABLE COUNTRY
    ADD CONSTRAINT FK_COUNTRY_Continent_ID 
    FOREIGN KEY (Continent_ID) 
    REFERENCES CONTINENT(Continent_ID);

ALTER TABLE COUNTRY_STATISTICS
    ADD CONSTRAINT FK_COUNTRY_STATISTICS_Country_ID 
    FOREIGN KEY (Country_ID) 
    REFERENCES COUNTRY(Country_ID);

ALTER TABLE COUNTRY_STATISTICS
    ADD CONSTRAINT FK_COUNTRY_STATISTICS_Year_ID 
    FOREIGN KEY (Year_ID) 
    REFERENCES YEAR(Year_ID);
